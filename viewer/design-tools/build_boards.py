def board(stem, cap, title, status, source, note=''):
    # a page is a drawer over the lens now; say so in its name so nobody looks for a page
    if 'pages/' in source and status == 'built' and not title.startswith('Phone') and not title.startswith('Tablet') and 'drawer' not in title.lower():
        title += ' · drawer'
    B[stem] = dict(stem=stem, cap=cap, title=title, status=status, source=source, note=note)

