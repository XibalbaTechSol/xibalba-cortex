class Check(HTMLParser):
    VOID = {'area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'param', 'source', 'track', 'wbr'}
    def __init__(s): super().__init__(); s.stack = []; s.errors = []; s.ids = set()
    def handle_starttag(s, tag, attrs):
        for k, v in attrs:
            if k == 'id':
                if v in s.ids: s.errors.append('duplicate id ' + v)
                s.ids.add(v)
        if tag not in s.VOID: s.stack.append(tag)
    def handle_startendtag(s, tag, attrs): pass
    def handle_endtag(s, tag):
        if tag in s.VOID: return
        if not s.stack or s.stack[-1] != tag: s.errors.append(f'mismatched </{tag}> (open: {s.stack[-3:]})')
        else: s.stack.pop()


def clean(markup, image_key):
    m = markup
    m = m.replace('src="/cortex-mark.png"', f'src="{MARK}"')
    m = re.sub(r'<button[^>]*>(?:(?!</button>).)*Connect to local Cortex</button>', '', m, flags=re.S)
    def canvas_to_img(match):
        tag = match.group(0)
        w = re.search(r'width="(\d+)"', tag).group(1); h = re.search(r'height="(\d+)"', tag).group(1)
        return f'<img src="{CANVAS_IMAGES[image_key]}" alt="" style="width: {w}px; height: {h}px; display: block">'
    m = re.sub(r'<canvas[^>]*></canvas>', canvas_to_img, m)
    assert '<canvas' not in m
    m = m.replace('{{', '&#123;&#123;').replace('}}', '&#125;&#125;').replace('\x00', '|')
    return m


