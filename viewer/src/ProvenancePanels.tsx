type ProofState = 'idle' | 'checking' | 'valid' | 'invalid'

// Runs a real hybrid_retrieve query and shows the full trace: per-channel ranks, RRF params,
// candidate pool sizes, graph edges, and a client-side-verified Merkle inclusion proof per
// result -- verification happens in the browser (merkleVerify.ts), not by trusting the server's
// own claim that a result belongs to the trace.
export function RetrievalTraceInspector({ onSelectMemory }: { onSelectMemory: (memoryId: string) => void }) {
  const [query, setQuery] = useState('')
  const [result, setResult] = useState<HybridRetrieveResult | null>(null)
  const [error, setError] = useState<string | null>(null)
  const [loading, setLoading] = useState(false)
  const [proofStates, setProofStates] = useState<Record<number, ProofState>>({})

  const runQuery = async () => {
    if (!query.trim()) return
    setLoading(true)
    setError(null)
    setProofStates({})
    try {
      const response = await api.hybridRetrieve({ query, limit: 10 })
      setResult(response)
    } catch (e) {
      setError(String(e))
    } finally {
      setLoading(false)
    }
  }

  const verifyRank = async (rank: number) => {
    if (!result) return
    setProofStates((prev) => ({ ...prev, [rank]: 'checking' }))
    try {
      const proof = await api.retrievalTraceEvidence(result.trace_id, rank)
      const valid = await verifyDomainMerkleProof(proof)
      setProofStates((prev) => ({ ...prev, [rank]: valid ? 'valid' : 'invalid' }))
    } catch {
      setProofStates((prev) => ({ ...prev, [rank]: 'invalid' }))
    }
  }

  return (
    <section className="overview-card" style={{ marginBottom: '24px' }}>
      <header className="overview-card-header">
        <div>
          <div className="overview-card-kicker">CRYPTOGRAPHIC PROOF</div>
          <div className="overview-card-title">Retrieval Trace Inspector</div>
        </div>
        {result && (
          <Badge>Trace ID: {result.trace_id.slice(0, 10)}…</Badge>
        )}
      </header>
      <div className="overview-card-body">
        <p className="small muted" style={{ margin: '0 0 16px 0' }}>
          Every query persists a full, independently verifiable execution trace. Click &ldquo;Verify inclusion proof&rdquo; to compute the Merkle root directly in this browser and verify that the retrieved item was cryptographically bound to the query execution.
        </p>
        <form
          className="tab-search-hero"
          style={{ marginBottom: '16px' }}
          onSubmit={(e) => {
            e.preventDefault()
            runQuery()
          }}
        >
          <Search size={16} className="search-icon" style={{ opacity: 0.6 }} />
          <input
            className="search-input"
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            placeholder="Search query text, a memory ID, or a sha256: content hash to inspect trace..."
          />
          <button className="small-button" type="submit" disabled={loading} style={{ padding: '6px 16px', display: 'flex', alignItems: 'center', gap: '6px' }}>
            {loading ? <RefreshCw size={13} className="spin-slow" /> : <Search size={13} />}
            {loading ? 'Searching…' : 'Inspect Trace'}
          </button>
        </form>
        {error && <p className="error-text">{error}</p>}
        {result && (
          <>
            <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', gap: '12px', margin: '14px 0', flexWrap: 'wrap' }}>
              <div style={{ display: 'flex', gap: '8px', flexWrap: 'wrap' }}>
                {Object.entries(result.channel_status).map(([channel, status]) => (
                  <Badge key={channel}>{channel}: {status}</Badge>
                ))}
              </div>
              <Badge>root <Hash value={result.root_hash} /></Badge>
            </div>
            {result.degraded.length > 0 && (
              <p className="small muted">{result.degraded.length} result(s) dropped by diversity/budget controls.</p>
            )}
            <div className="item-list" style={{ maxHeight: '520px', overflowY: 'auto', paddingRight: '6px' }}>
              {result.results.map((memory, i) => {
                const rank = i + 1
                const proofState = proofStates[rank] ?? 'idle'
                return (
                  <article className="item" key={memory.id} style={{ background: 'rgba(10, 14, 20, 0.65)', border: '1px solid var(--border)', borderRadius: '8px', padding: '14px', marginBottom: '10px' }}>
                    <div className="item-head" style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: '8px' }}>
                      <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
                        <strong style={{ color: 'var(--accent)', fontSize: '13px' }}>Rank #{rank}</strong>
                        <Badge>{memory.evidence_class}</Badge>
                      </div>
                      <div style={{ display: 'flex', alignItems: 'center', gap: '6px' }}>
                        {proofState === 'valid' && (
                          <span style={{ display: 'inline-flex', alignItems: 'center', gap: '4px', fontSize: '11px', color: '#4ade80', fontWeight: 600 }}>
                            <CheckCircle2 size={13} /> Merkle verified
                          </span>
                        )}
                        {proofState === 'invalid' && (
                          <span style={{ display: 'inline-flex', alignItems: 'center', gap: '4px', fontSize: '11px', color: '#fb7185', fontWeight: 600 }}>
                            <XCircle size={13} /> Verification failed
                          </span>
                        )}
                      </div>
                    </div>
                    <p className="small" style={{ margin: '6px 0', lineHeight: '1.45' }}>{memory.content.slice(0, 240)}</p>
                    <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginTop: '10px', flexWrap: 'wrap', gap: '8px' }}>
                      <p className="small muted" style={{ margin: 0 }}>content hash <Hash value={memory.content_hash} /></p>
                      <div className="action-row" style={{ display: 'flex', gap: '8px' }}>
                        <button type="button" className="small-button" onClick={() => onSelectMemory(memory.id)}>Inspect memory</button>
                        <button
                          type="button"
                          className="small-button"
                          disabled={proofState === 'checking'}
                          onClick={() => verifyRank(rank)}
                          style={proofState === 'valid' ? { borderColor: '#4ade80', color: '#4ade80' } : {}}
                        >
                          {proofState === 'checking' ? 'Verifying…' : proofState === 'valid' ? 'Re-verify Proof' : 'Verify inclusion proof'}
                        </button>
                      </div>
                    </div>
                  </article>
                )
              })}
            </div>
          </>
        )}
      </div>
    </section>
  )
}

// Projection checkpoint/reconciliation status -- recompute from canonical SQLite, compare
// against the last stored checkpoint, and show whether a projection is degraded, not just
// assert it's fine.
export function ProjectionHealthPanel() {
  const [projectionId, setProjectionId] = useState('memories')
  const [checkpoints, setCheckpoints] = useState<ProjectionCheckpoint[]>([])
  const [reconciliation, setReconciliation] = useState<ProjectionReconciliation | null>(null)
  const [error, setError] = useState<string | null>(null)
  const [busy, setBusy] = useState(false)

  const refresh = async (id: string) => {
    try {
      const history = await api.projectionCheckpoints(id)
      setCheckpoints(history)
      setError(null)
    } catch (e) {
      setError(String(e))
    }
  }

  const runAction = async (action: 'checkpoint' | 'reconcile' | 'rebuild') => {
    setBusy(true)
    setError(null)
    try {
      if (action === 'checkpoint') await api.createProjectionCheckpoint(projectionId)
      if (action === 'rebuild') await api.rebuildProjectionCheckpoint(projectionId)
      if (action === 'reconcile') setReconciliation(await api.reconcileProjectionCheckpoint(projectionId))
      await refresh(projectionId)
    } catch (e) {
      setError(String(e))
    } finally {
      setBusy(false)
    }
  }

  return (
    <section className="overview-card">
      <header className="overview-card-header">
        <div>
          <div className="overview-card-kicker">DRIFT DETECTION</div>
          <div className="overview-card-title">Projection Health &amp; Checkpoints</div>
        </div>
        <select
          className="session-select form-select"
          value={projectionId}
          onChange={(e) => {
            setProjectionId(e.target.value)
            refresh(e.target.value)
          }}
          style={{ fontSize: '11px', padding: '4px 10px' }}
        >
          <option value="memories">memories</option>
          <option value="entities">entities</option>
          <option value="relations">relations</option>
        </select>
      </header>
      <div className="overview-card-body">
        <p className="small muted" style={{ margin: '0 0 14px 0' }}>
          Checkpoints recompute from canonical SQLite — state drift is flagged explicitly, not silently served.
        </p>
        <div className="action-row" style={{ marginBottom: '16px', display: 'flex', gap: '8px', flexWrap: 'wrap' }}>
          <button type="button" className="small-button" disabled={busy} onClick={() => runAction('checkpoint')}>
            Create checkpoint
          </button>
          <button type="button" className="small-button" disabled={busy} onClick={() => runAction('reconcile')}>
            Reconcile
          </button>
          <button type="button" className="small-button" disabled={busy} onClick={() => runAction('rebuild')}>
            Rebuild &amp; verify
          </button>
          <button type="button" className="small-button" disabled={busy} onClick={() => refresh(projectionId)}>
            Refresh
          </button>
        </div>
        {error && <p className="error-text">{error}</p>}
        {reconciliation && (
          <div className="item" style={{ marginBottom: '14px', background: 'rgba(10, 14, 20, 0.65)', border: '1px solid var(--border)', borderRadius: '8px', padding: '12px' }}>
            <div className="item-head" style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: '6px' }}>
              <strong>Last reconciliation</strong>
              <Badge>{reconciliation.equal ? 'equal' : reconciliation.action}</Badge>
            </div>
            {!reconciliation.equal && (
              <p className="small muted" style={{ margin: 0 }}>
                missing: {reconciliation.missing.length}, extra: {reconciliation.extra.length}, reordered: {String(reconciliation.reordered)}
              </p>
            )}
          </div>
        )}
        {checkpoints.length === 0 ? (
          <div className="empty-state">
            <h4>No checkpoints yet</h4>
            <p>Create one to establish a baseline for this projection.</p>
          </div>
        ) : (
          <div className="item-list" style={{ maxHeight: '360px', overflowY: 'auto', paddingRight: '6px' }}>
            {checkpoints.map((checkpoint) => (
              <article className="item" key={checkpoint.id} style={{ background: 'rgba(10, 14, 20, 0.65)', border: '1px solid var(--border)', borderRadius: '8px', padding: '12px', marginBottom: '8px' }}>
                <div className="item-head" style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: '6px' }}>
                  <strong style={{ color: 'var(--accent)' }}>{checkpoint.leaf_count} leaves</strong>
                  <Badge>{checkpoint.status}</Badge>
                </div>
                <p className="small muted" style={{ margin: '4px 0' }}>root <Hash value={checkpoint.root_hash} /></p>
                <p className="small muted" style={{ margin: 0 }}>{checkpoint.created_at}</p>
              </article>
            ))}
          </div>
        )}
      </div>
    </section>
  )
}

