function getTaskTypeStyle(taskType: string) {
  switch (taskType) {
    case 'extract_entities':
      return { color: '#38bdf8', bg: 'rgba(56, 189, 248, 0.12)', border: 'rgba(56, 189, 248, 0.3)' }
    case 'extract_relations':
      return { color: '#c084fc', bg: 'rgba(192, 132, 252, 0.12)', border: 'rgba(192, 132, 252, 0.3)' }
    case 'classify_para':
      return { color: '#4ade80', bg: 'rgba(74, 222, 128, 0.12)', border: 'rgba(74, 222, 128, 0.3)' }
    case 'detect_contradictions':
      return { color: '#fb7185', bg: 'rgba(251, 113, 133, 0.12)', border: 'rgba(251, 113, 133, 0.3)' }
    default:
      return { color: '#93c5fd', bg: 'rgba(147, 197, 253, 0.12)', border: 'rgba(147, 197, 253, 0.3)' }
  }
}

