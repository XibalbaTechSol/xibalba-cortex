"""Emit a Foundry test that checks this package's root and proofs against the real contract.

    uv run python scripts/gen_forge_crosscheck.py tests/fixtures/toy_toolgraph.json \
        > <integrity-core contracts project>/test/CortexNavCrossCheck.t.sol
    forge test --match-path test/CortexNavCrossCheck.t.sol -vv

The generated test deploys `PolicyRegistry`, stores the Python-computed root with
`setGraphRoot`, and asserts that `checkGraphEdge` accepts every Python-generated proof and
rejects tampered ones. `--golden` prints the root, leaves and proofs as JSON instead (the
content of `tests/fixtures/toy_toolgraph.golden.json`).
"""

from __future__ import annotations

import argparse
import json

from eth_utils import to_checksum_address

from cortex_nav.anchor import graph_root, merkle_proof
from cortex_nav.canonical import node_id
from cortex_nav.graph import Edge, load_toolgraph


def _hex(value: bytes) -> str:
    return "0x" + value.hex()


def _args(edge: Edge, *, risk: int | None = None) -> str:
    return ", ".join(
        [
            "DOMAIN",
            _hex(edge.from_node),
            _hex(edge.relation),
            _hex(edge.to_node),
            to_checksum_address(edge.target),
            "bytes4(" + _hex(edge.target_selector) + ")",
            str(edge.risk_weight_bps if risk is None else risk),
        ]
    )


def _proof_fn(name: str, proof: list[bytes]) -> str:
    lines = [f"    function {name}() internal pure returns (bytes32[] memory p) {{", f"        p = new bytes32[]({len(proof)});"]
    lines += [f"        p[{i}] = {_hex(node)};" for i, node in enumerate(proof)]
    return "\n".join([*lines, "    }"])


def golden(graph) -> dict:
    return {
        "root": _hex(graph_root(graph)),
        "edges": [
            {"leaf": _hex(e.leaf), "proof": [_hex(p) for p in merkle_proof(graph, e)]} for e in graph.edges
        ],
    }


def solidity(graph) -> str:
    edges = graph.edges
    proofs = [merkle_proof(graph, e) for e in edges]
    fake = Edge(
        from_node=edges[0].from_node,
        relation=node_id("tool:teleport"),
        to_node=edges[-1].to_node,
        target=bytes(20),
        target_selector=bytes(4),
        risk_weight_bps=0,
        grounded=True,
        r_task=0.0,
    )
    assert fake not in graph
    accept, reject = [], []
    for i, edge in enumerate(edges):
        no_domain = _args(edge).removeprefix("DOMAIN, ")
        accept.append(f"        assertEq(registry.leafOf({no_domain}), {_hex(edge.leaf)});")
        accept.append(f"        assertTrue(registry.checkGraphEdge({_args(edge)}, _proof{i}()));")
        reject.append(f"        assertFalse(registry.checkGraphEdge({_args(edge, risk=edge.risk_weight_bps + 1)}, _proof{i}()));")
        reject.append(f"        assertFalse(registry.checkGraphEdge({_args(fake)}, _proof{i}()));")
        reject.append(f"        assertFalse(registry.checkGraphEdge({_args(edge)}, _proof{(i + 1) % len(edges)}()));")
        reject.append(f"        assertFalse(registry.checkGraphEdge({_args(edge).replace('DOMAIN', 'OTHER_DOMAIN', 1)}, _proof{i}()));")
        if proofs[i]:
            reject.append(f"        p = _proof{i}();")
            reject.append("        p[0] = p[0] ^ bytes32(uint256(1));")
            reject.append(f"        assertFalse(registry.checkGraphEdge({_args(edge)}, p));")
    body = "\n\n".join(_proof_fn(f"_proof{i}", p) for i, p in enumerate(proofs))
    return f"""// SPDX-License-Identifier: MIT
// GENERATED by xibalba-cortex cortex-nav/scripts/gen_forge_crosscheck.py. Temporary; do not commit.
pragma solidity ^0.8.28;

import {{Test}} from "forge-std/Test.sol";
import {{PolicyRegistry}} from "../src/trust/PolicyRegistry.sol";

contract CortexNavCrossCheckTest is Test {{
    PolicyRegistry registry;
    bytes32 constant DOMAIN = keccak256("cortex-nav-crosscheck");
    bytes32 constant OTHER_DOMAIN = keccak256("cortex-nav-crosscheck-unset");
    bytes32 constant PYTHON_ROOT = {_hex(graph_root(graph))};

    function setUp() public {{
        registry = new PolicyRegistry(address(this));
        registry.setGraphRoot(DOMAIN, PYTHON_ROOT);
    }}

{body}

    function test_contractAcceptsEveryPythonProof_{len(edges)}Edges() public view {{
        assertEq(registry.graphRootOf(DOMAIN), PYTHON_ROOT);
{chr(10).join(accept)}
    }}

    function test_contractRejectsTamperedEdgesAndProofs() public view {{
        bytes32[] memory p;
{chr(10).join(reject)}
    }}
}}
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("fixture")
    parser.add_argument("--golden", action="store_true")
    args = parser.parse_args()
    graph = load_toolgraph(args.fixture)
    print(json.dumps(golden(graph), indent=2) if args.golden else solidity(graph), end="\n" if args.golden else "")


if __name__ == "__main__":
    main()
